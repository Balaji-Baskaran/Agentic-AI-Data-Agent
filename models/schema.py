from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages: Annotated[list,add] =  Field(..., description="A list of messages to be processed by the agent.")
    user_question: str = Field(..., description= "A real question asked by  the user")
    curated_user_prompt: str = Field(..., description="A curated user question")
    prompt_query_context : str = Field(..., description="A detailed prompt with SQL DB context that help agent to generate a SQL Query ")
    generated_sql_query: str = Field(..., description="The SQL query generated by the agent based on the curated question and prompt context")
    sql_query_execution_result: str = Field(..., description="The result of executing the generated SQL Query on the database")
    is_safe: Literal["Yes","No"] = Field(..., description= "Indicates whether the generate SQL query is safe to execute or not")
    comment: str = Field(..., description = "An additional comment or feedback from the judge regarding the query")
    final_answer: str = Field(..., description="The final answer genrated by the agent based on the sql query execution result and the curated question")
    

class JudgeSchema(BaseModel):
    
    answer : Literal['Yes', 'No'] = Field(..., description= "Indicates whether the generated SQL query is safe to execute or not")
    comment: str = Field(..., description = "An additional comment or feedback from the judge regarding the query")
   
class ETLAgentSchema(BaseModel):
     messages : Annotated[list,add] = Field(..., description= "List of messages processed by the ETL Agent")
     

class RouterSchema(BaseModel):
    answer : Literal["SQL","ETL"] = Field(..., description = "Indicates Whether a User's question is related to the SQL or ETL Agent")
    comments: str = Field(..., description = "Additional Comments or feedback regarding the classification of the User's question")
    
    
class DataAgentSchema(BaseModel):
    messages : Annotated[list, add] = Field(..., description = "List of messages to be processed by the Data agent")
    route_response : str = Field(..., description="The response from the router indicating whether to route to SQL or ETL operations")